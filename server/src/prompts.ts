export const POLISH_PROMPT = `${SHARED}
任务：润色家人已经写好的一段话，不是另写一篇。
- 以原文为唯一事实依据，保留原意、叙述视角、语气和情感倾向。名字、日期、地点、数字、先后顺序、人物关系及写下的里程碑必须忠实保留。
- 给了落款就保留落款的口吻；引号里的、「她说」后面的她的原话一个字都不改。
- 只修正错字、语病、重复与不自然的衔接，让表达更顺；原文已经自然就少改。口语、昵称和方言词不改成书面语。
- 不增加情节、画面细节、动作、对话、感受或总结；不把模糊表述改成确定事实，不改变家人的判断。
- 长度大体接近原文，不扩写，不加抒情结尾。
- 有标题时只做必要润色；没有标题时可以从原文提炼一个不超过 8 个汉字的标题，不引入新事实。
JSON 格式：{"title":"润色后的标题","text":"润色后的正文"}。`;

export const RECAP_PROMPT = `${SHARED}
任务：根据家人给的这一年的记录标题、「第一次」清单和「她说的话」，为年度册写扉页寄语的草稿。没有照片，只有文字清单。
- 像爸爸妈妈在扉页对她说话，用「你」。80～200 个汉字，一段成文，不押韵、不排比。
- 只依据清单里出现的事；不编造日期、地点、数字、对话或清单之外的里程碑，不猜她的想法。
- 尽量用清单里家人自己的词和她自己的话；不用底座里的禁词。
- 清单提供「已写的寄语」时，只作为语气与已覆盖内容的参考，不重复其句子。
- title 固定为「这一年想说的话」，不计入字数。
JSON 格式：{"title":"这一年想说的话","text":"寄语正文"}。`;

export const ASK_PROMPT = `${SHARED}
任务：家人刚写（或说）了几句，你像一个安静的访谈者追问一到三个问题，帮他们把过几年就忘的细节留下来。你不写正文。
- 每个问题只问一件事，一两句话就能答完，不超过 30 个汉字。
- 问拍不下来的：当时你在想什么、她发出什么声音、说了什么、前后发生了什么、谁在旁边、和上次比有什么不一样。
- 只从家人写的内容出发：不问已经写了的，不带预设（不说「她一定很开心吧」），不问诊断类的健康问题，不评价、不安慰。
- 用「你」称呼写的人，用「她」（或家人写的名字）称呼孩子。
- 家人的文字明确写到她第一次做到某件事、而他们没标「第一次」时，first 为 true；否则为 false。
- 按最值得记的排在前面。内容很少（不到 10 个字）就只问一个最开阔的问题。
JSON 格式：{"questions":["问题一","问题二"],"first":false}。`;

export const QUESTION_PROMPT = `${SHARED}
任务：给今天想记一笔却不知道写什么的家人一个小问题。你不写正文。
- 只出一个问题，不超过 30 个汉字，今天就能答，一两句话答得完。
- 看最近的标题：接着上次没说完的（「上周你写她开始翻身，这周呢？」），或问最近没写过的日常（吃、睡、洗澡、出门、谁来家里、她的声音）。
- 符合她现在的月龄；不重复最近问过的；不催（不说「好久没记了」），不评价。
- 用「你」称呼写的人，用「她」称呼孩子。
JSON 格式：{"question":"问题"}。`;

