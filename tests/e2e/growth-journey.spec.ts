test.use({permissions:['microphone'],launchOptions:{args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']}});
test('restoring an unsent private recording preserves its audience in the form and saved contribution',async({page})=>{
  await ensureBootstrap(page);
  await page.goto('/capture');
  await page.getByLabel('写下这一刻').fill('这段声音只留给自己。');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  const memoryLink=page.getByRole('link',{name:'查看这条记忆'});
  await expect(memoryLink).toBeVisible();
  const memoryPath=(await memoryLink.getAttribute('href'))!;
  await memoryLink.click();
  await page.locator('select[name="visibility"]').selectOption('private');
  const author=await page.locator('select[name="authorPersonId"]').inputValue();
  await page.getByRole('button',{name:'留段声音',exact:true}).click();
  await expect(page.getByText('录音中，完成后保存在本机。')).toBeVisible();
  await page.waitForTimeout(1200);
  await page.getByRole('button',{name:'完成录音'}).click();
  await expect(page.getByLabel('重听待保存的声音')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('重听待保存的声音')).toBeVisible();
  await expect(page.locator('select[name="visibility"]')).toHaveValue('private');
  await expect(page.locator('select[name="authorPersonId"]')).toHaveValue(author);
  await expect(page.getByText('· 仅自己 · 本机录音',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'保存声音',exact:true}).click();
  await expect(page.getByText('声音已保存到这条成长记录。')).toBeVisible();
  const memory=await(await page.request.get('/api/mobile/v1'+memoryPath)).json();
  const voices=memory.contributions.filter((c:{audioPath:string|null})=>c.audioPath);
  expect(voices).toHaveLength(1);
  expect(voices[0]).toMatchObject({authorPersonId:author,visibility:'private'});
});
