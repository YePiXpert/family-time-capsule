  await page.getByRole('button',{name:'保存',exact:true}).click();
  const link=page.getByRole('link',{name:'查看这条记忆'});await expect(link).toBeVisible();
  const memoryPath=(await link.getAttribute('href'))!;
  await link.click();
  await page.getByRole('button',{name:'第一次',exact:true}).click();
  await expect(page.getByRole('button',{name:'第一次',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByLabel('补充文字讲述').fill('爸爸记得你的小手很暖。');
  await page.getByRole('button',{name:'保存这段讲述'}).click();
