export function promptsFor(band: PromptBand): readonly string[] {
  return PROMPTS[band];
}

/** 虚岁月龄（整月）；未填或无效生日、生日在未来返回 null。 */
export function ageInMonths(
  birthday: string,
  today = new Date(),
): number | null {
  const born = parseBirthday(birthday);
  if (!born) return null;
  const t = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  if (t.getTime() < born.getTime()) return null;
  let months =
    (t.getFullYear() - born.getFullYear()) * 12 +
    (t.getMonth() - born.getMonth());
  if (t.getDate() < born.getDate()) months--;
  return Math.max(0, months);
}

export function bandOf(birthday: string, today = new Date()): PromptBand {
  const months = ageInMonths(birthday, today);
  if (months === null) return "0-6m";
  if (months < 6) return "0-6m";
  if (months < 12) return "6-12m";
  if (months < 24) return "1-2y";
  if (months < 48) return "2-4y";
  return "4y+";
}

function hashOf(value: string): number {
  let h = 2166136261;
  for (let i = 0; i < value.length; i++) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** 同一天同一 seed 稳定返回一条；「换一个」换 seed 即可，不落库。 */
export function promptOf(birthday: string, today: Date, seed = 0): string {
  const band = bandOf(birthday, today);
  const list = PROMPTS[band];
  const day = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
  return list[hashOf(`${band}|${day}|${seed}`) % list.length]!;
}
